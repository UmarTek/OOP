/*
 Ответы на вопросы:
 
 1. Почему первый массив не изменился?
 Потому что массивы в Swift являются структурами (Value Types) и обладают значимой семантикой. 
 Изменение одной переменной никак не может повлиять на другую.

 2. Обязан ли Swift физически копировать миллион элементов в момент присваивания?
 Нет, не обязан и не делает этого. Благодаря оптимизации Copy-on-Write (COW), в момент выполнения 
 строки `var secondArray = firstArray` обе переменные начинают указывать на один и тот же внутренний 
 буфер памяти в куче (heap).

 3. В какой момент реализация может создать отдельный буфер?
 Реальное физическое копирование элементов в новый буфер происходит ровно в тот момент, когда 
 один из массивов пытается себя изменить (в нашем случае — при вызове `secondArray.append(...)`), 
 и Swift обнаруживает, что на этот буфер памяти ссылается более чем одна переменная.

 4. Почему copy-on-write не превращает Array в ссылочный тип?
 COW — это скрытая деталь реализации под капотом, служащая исключительно для оптимизации производительности. 
 С точки зрения разработчика и архитектуры кода, массив внешне ведет себя строго как значимый тип: 
 данные защищены от скрытого совместного изменения, обеспечивая предсказуемую значимую семантику.
*/
